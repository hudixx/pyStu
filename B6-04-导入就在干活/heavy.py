"""被 04_导入.py 导入。模块体里调用 build，所以第一次 import 就会做完这段循环。

对照一个类的静态初始化块。加载这个模块时，文件里不在函数中的代码会从上到下执行。
函数定义本身只是把函数造出来，不会跑里面的循环。真正跑循环的是文件最后那一行对 build 的调用。
"""

from __future__ import annotations


def build() -> int:
    """这段循环不该在 import 时跑。放在函数里，再在模块体调用，第一次导入仍会跑。

    逻辑：把 0 到 99999 加起来返回。单独定义它不会执行循环。
    谁在 import 期间调用了它，第一次导入就要付这段时间。
    """
    print("进入方法")
    total = 0
    for i in range(100_000):
        # range(100_000) 是 0 到 99999。下划线只方便读，值是十万。
        total += i
    return total


built = build()  # 这一行在 import 时执行。第二次 import 不会再来。
# 它不在任何函数里，所以属于模块体。导入这个文件就会调用 build，把结果放进模块级名字 built。
# 对照静态字段在类加载时就算好。同一次进程里再次 import，解释器直接用已经加载的模块，这一行不执行。

# 这个文件想说明的事：
# 把重活放进函数，并不等于导入时不跑。模块体若调用了它，第一次 import 仍会把循环做完。
# 不想在导入时付钱，就不要在模块体里调用。让使用方在真正需要时再 build()。
